package com.ternbusty.takoyaki.ffigen;

import java.io.IOException;
import java.lang.foreign.AddressLayout;
import java.lang.foreign.GroupLayout;
import java.lang.foreign.MemoryLayout;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.SequenceLayout;
import java.lang.foreign.ValueLayout;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.stream.Stream;

/**
 * Build-time generator for struct accessors with constant layouts.
 *
 * <p>jextract emits one class per struct or union, whose static initializer
 * builds the {@code MemoryLayout} tree and selects every field from it. Those
 * classes live in {@code syscall.gen}, which must be initialized at run time
 * because the layouts they use are declared next to the symbol lookup. So
 * each struct class costs code in the image and layout construction at run
 * time when it is first touched (bpf_attr alone compiled to ~280 KiB of
 * static initializers).
 *
 * <p>This generator reads the compiled jextract struct classes by reflection
 * and writes a class with the same name and the same field accessors to
 * {@code ffi.structs}. Field offsets, sizes and alignments are taken from the
 * jextract layouts ({@code <field>$offset()}, {@code <field>$layout()}) and
 * written as constants, and value layouts are rebuilt from the
 * {@code ValueLayout.JAVA_*} constants; every rebuilt layout is checked to be
 * equal to the jextract one. The package is initialized at build time, so
 * nothing is computed at run time.
 *
 * <p>Generated per struct: {@code sizeof()}, {@code alignof()},
 * {@code allocate}, {@code allocateArray}, {@code asSlice}, and per field
 * {@code <field>$offset()}, a getter and a setter (a slice for nested structs and arrays, plus indexed
 * accessors for one-dimensional arrays of values), and a nested class per
 * nested struct that jextract gives a class to.
 *
 * <p>Usage: {@code GenerateStructs <output source dir> <jextract source dir>}
 */
public final class GenerateStructs {
    private static final String IN_PKG = "com.ternbusty.takoyaki.syscall.gen";
    private static final String OUT_PKG = "com.ternbusty.takoyaki.ffi.structs";

    /** Same definition as jextract's C_POINTER. */
    private static final AddressLayout C_POINTER = ValueLayout.ADDRESS.withTargetLayout(
            MemoryLayout.sequenceLayout(Long.MAX_VALUE, ValueLayout.JAVA_BYTE));

    private GenerateStructs() {}

    public static void main(String[] args) throws Exception {
        Path out = Path.of(args[0]);
        Path in = Path.of(args[1]).resolve(IN_PKG.replace('.', '/'));
        List<String> names;
        try (Stream<Path> files = Files.list(in)) {
            names = files.map(p -> p.getFileName().toString())
                    .filter(f -> f.endsWith(".java") && !f.startsWith("NativeHRaw"))
                    .map(f -> f.substring(0, f.length() - ".java".length()))
                    .sorted()
                    .toList();
        }
        int count = 0;
        for (String name : names) {
            Class<?> c = Class.forName(IN_PKG + "." + name, false, GenerateStructs.class.getClassLoader());
            if (groupLayout(c) == null) continue;
            StringBuilder sb = new StringBuilder();
            sb.append("package ").append(OUT_PKG).append(";\n\n")
              .append("import java.lang.foreign.AddressLayout;\n")
              .append("import java.lang.foreign.MemoryLayout;\n")
              .append("import java.lang.foreign.MemorySegment;\n")
              .append("import java.lang.foreign.SegmentAllocator;\n")
              .append("import java.lang.foreign.ValueLayout;\n")
              .append("import java.util.Objects;\n\n")
              .append("/**\n")
              .append(" * Accessors for {@code ").append(IN_PKG).append('.').append(name)
              .append("} with constant offsets.\n")
              .append(" * Generated by GenerateStructs from the jextract layout; do not edit.\n")
              .append(" */\n")
              .append("@SuppressWarnings(\"unused\")\n");
            writeClass(sb, c, "", true);
            Path dir = out.resolve(OUT_PKG.replace('.', '/'));
            Files.createDirectories(dir);
            Files.writeString(dir.resolve(name + ".java"), sb);
            count++;
        }
        System.out.printf("GenerateStructs: %d structs and unions%n", count);
    }

    /** The class's own {@code layout()}, or null if it is not a jextract struct or union class. */
    private static GroupLayout groupLayout(Class<?> c) throws ReflectiveOperationException {
        Method m;
        try {
            m = c.getDeclaredMethod("layout");
        } catch (NoSuchMethodException e) {
            return null;
        }
        if (!Modifier.isStatic(m.getModifiers()) || !GroupLayout.class.isAssignableFrom(m.getReturnType())) {
            return null;
        }
        return (GroupLayout) m.invoke(null);
    }

    private record Field(String name, long offset, MemoryLayout layout) {}

    private static void writeClass(StringBuilder sb, Class<?> c, String indent, boolean top)
            throws ReflectiveOperationException {
        GroupLayout layout = groupLayout(c);
        String name = c.getSimpleName();
        List<Field> fields = fields(c);
        sb.append(indent).append(top ? "public final class " : "public static final class ")
          .append(name).append(" {\n");
        String in = indent + "    ";
        sb.append(in).append("private ").append(name).append("() {}\n\n")
          .append(in).append("private static final long SIZE = ").append(layout.byteSize()).append("L;\n")
          .append(in).append("private static final long ALIGN = ").append(layout.byteAlignment()).append("L;\n");
        if (fields.stream().anyMatch(GenerateStructs::usesPointer)) {
            sb.append(in).append("private static final AddressLayout C_POINTER = ValueLayout.ADDRESS.withTargetLayout(\n")
              .append(in).append("        MemoryLayout.sequenceLayout(Long.MAX_VALUE, ValueLayout.JAVA_BYTE));\n");
        }
        sb.append('\n')
          .append(in).append("public static long sizeof() { return SIZE; }\n\n")
          .append(in).append("public static long alignof() { return ALIGN; }\n\n")
          .append(in).append("public static MemorySegment allocate(SegmentAllocator allocator) {\n")
          .append(in).append("    return allocator.allocate(SIZE, ALIGN);\n")
          .append(in).append("}\n\n")
          .append(in).append("public static MemorySegment allocateArray(long elementCount, SegmentAllocator allocator) {\n")
          .append(in).append("    return allocator.allocate(SIZE * elementCount, ALIGN);\n")
          .append(in).append("}\n\n")
          .append(in).append("public static MemorySegment asSlice(MemorySegment array, long index) {\n")
          .append(in).append("    return array.asSlice(SIZE * index);\n")
          .append(in).append("}\n");

        for (Field f : fields) {
            writeField(sb, in, f);
        }
        List<Class<?>> nested = new ArrayList<>();
        for (Class<?> n : c.getDeclaredClasses()) {
            if (Modifier.isPublic(n.getModifiers()) && groupLayout(n) != null) nested.add(n);
        }
        nested.sort(Comparator.comparing(Class::getSimpleName));
        for (Class<?> n : nested) {
            sb.append('\n');
            writeClass(sb, n, in, false);
        }
        sb.append(indent).append("}\n");
    }

    private static boolean usesPointer(Field f) {
        MemoryLayout l = f.layout() instanceof SequenceLayout s ? s.elementLayout() : f.layout();
        return l instanceof AddressLayout a && a.targetLayout().isPresent();
    }

    /** Fields jextract exposes through {@code <name>$offset()} and {@code <name>$layout()}. */
    private static List<Field> fields(Class<?> c) throws ReflectiveOperationException {
        List<Field> fs = new ArrayList<>();
        for (Method m : c.getDeclaredMethods()) {
            String n = m.getName();
            if (!n.endsWith("$offset") || m.getParameterCount() != 0 || !Modifier.isStatic(m.getModifiers())
                    || !Modifier.isPublic(m.getModifiers())) {
                continue;
            }
            String field = n.substring(0, n.length() - "$offset".length());
            long offset = (long) m.invoke(null);
            MemoryLayout l = (MemoryLayout) c.getDeclaredMethod(field + "$layout").invoke(null);
            fs.add(new Field(field, offset, l));
        }
        fs.sort(Comparator.comparingLong(Field::offset).thenComparing(Field::name));
        return fs;
    }

    private static void writeField(StringBuilder sb, String in, Field f) {
        String n = f.name();
        sb.append('\n').append(in).append("private static final long ").append(n).append("$OFFSET = ")
          .append(f.offset()).append("L;\n");
        sb.append('\n').append(in).append("public static long ").append(n).append("$offset() { return ")
          .append(n).append("$OFFSET; }\n");
        if (f.layout() instanceof ValueLayout v) {
            String type = carrierName(v);
            sb.append(in).append("private static final ").append(layoutType(v)).append(' ').append(n)
              .append("$LAYOUT = ").append(valueLayoutExpr(v)).append(";\n\n")
              .append(in).append("public static ").append(type).append(' ').append(n)
              .append("(MemorySegment struct) {\n")
              .append(in).append("    return struct.get(").append(n).append("$LAYOUT, ").append(n).append("$OFFSET);\n")
              .append(in).append("}\n\n")
              .append(in).append("public static void ").append(n).append("(MemorySegment struct, ").append(type)
              .append(" fieldValue) {\n")
              .append(in).append("    struct.set(").append(n).append("$LAYOUT, ").append(n)
              .append("$OFFSET, fieldValue);\n")
              .append(in).append("}\n");
            return;
        }
        // A nested struct, union or array: a slice of the enclosing struct.
        sb.append(in).append("private static final long ").append(n).append("$SIZE = ")
          .append(f.layout().byteSize()).append("L;\n\n")
          .append(in).append("public static MemorySegment ").append(n).append("(MemorySegment struct) {\n")
          .append(in).append("    return struct.asSlice(").append(n).append("$OFFSET, ").append(n).append("$SIZE);\n")
          .append(in).append("}\n\n")
          .append(in).append("public static void ").append(n).append("(MemorySegment struct, MemorySegment fieldValue) {\n")
          .append(in).append("    MemorySegment.copy(fieldValue, 0L, struct, ").append(n).append("$OFFSET, ")
          .append(n).append("$SIZE);\n")
          .append(in).append("}\n");
        if (f.layout() instanceof SequenceLayout s && s.elementLayout() instanceof ValueLayout e) {
            String type = carrierName(e);
            sb.append('\n')
              .append(in).append("private static final ").append(layoutType(e)).append(' ').append(n)
              .append("$ELEM = ").append(valueLayoutExpr(e)).append(";\n")
              .append(in).append("private static final long ").append(n).append("$COUNT = ")
              .append(s.elementCount()).append("L;\n\n")
              .append(in).append("public static ").append(type).append(' ').append(n)
              .append("(MemorySegment struct, long index0) {\n")
              .append(in).append("    return struct.get(").append(n).append("$ELEM, ").append(n).append("$OFFSET + ")
              .append(e.byteSize()).append("L * Objects.checkIndex(index0, ").append(n).append("$COUNT));\n")
              .append(in).append("}\n\n")
              .append(in).append("public static void ").append(n).append("(MemorySegment struct, long index0, ")
              .append(type).append(" fieldValue) {\n")
              .append(in).append("    struct.set(").append(n).append("$ELEM, ").append(n).append("$OFFSET + ")
              .append(e.byteSize()).append("L * Objects.checkIndex(index0, ").append(n)
              .append("$COUNT), fieldValue);\n")
              .append(in).append("}\n");
        }
    }

    private static String carrierName(ValueLayout v) {
        Class<?> c = v.carrier();
        return c == MemorySegment.class ? "MemorySegment" : c.getName();
    }

    private static String layoutType(ValueLayout v) {
        return switch (v) {
            case AddressLayout a -> "AddressLayout";
            case ValueLayout.OfBoolean b -> "ValueLayout.OfBoolean";
            case ValueLayout.OfByte b -> "ValueLayout.OfByte";
            case ValueLayout.OfChar ch -> "ValueLayout.OfChar";
            case ValueLayout.OfShort s -> "ValueLayout.OfShort";
            case ValueLayout.OfInt i -> "ValueLayout.OfInt";
            case ValueLayout.OfLong l -> "ValueLayout.OfLong";
            case ValueLayout.OfFloat fl -> "ValueLayout.OfFloat";
            case ValueLayout.OfDouble d -> "ValueLayout.OfDouble";
        };
    }

    /**
     * Java source for a layout equal to {@code v} (ignoring its name), built
     * from the JAVA_* constants. Fails if the rebuilt layout differs.
     */
    private static String valueLayoutExpr(ValueLayout v) {
        MemoryLayout base;
        String expr;
        switch (v) {
            case AddressLayout a -> {
                if (a.targetLayout().isPresent()) {
                    base = C_POINTER;
                    expr = "C_POINTER";
                } else {
                    base = ValueLayout.ADDRESS;
                    expr = "ValueLayout.ADDRESS";
                }
            }
            case ValueLayout.OfBoolean b -> { base = ValueLayout.JAVA_BOOLEAN; expr = "ValueLayout.JAVA_BOOLEAN"; }
            case ValueLayout.OfByte b -> { base = ValueLayout.JAVA_BYTE; expr = "ValueLayout.JAVA_BYTE"; }
            case ValueLayout.OfChar ch -> { base = ValueLayout.JAVA_CHAR; expr = "ValueLayout.JAVA_CHAR"; }
            case ValueLayout.OfShort s -> { base = ValueLayout.JAVA_SHORT; expr = "ValueLayout.JAVA_SHORT"; }
            case ValueLayout.OfInt i -> { base = ValueLayout.JAVA_INT; expr = "ValueLayout.JAVA_INT"; }
            case ValueLayout.OfLong l -> { base = ValueLayout.JAVA_LONG; expr = "ValueLayout.JAVA_LONG"; }
            case ValueLayout.OfFloat fl -> { base = ValueLayout.JAVA_FLOAT; expr = "ValueLayout.JAVA_FLOAT"; }
            case ValueLayout.OfDouble d -> { base = ValueLayout.JAVA_DOUBLE; expr = "ValueLayout.JAVA_DOUBLE"; }
        }
        if (v.byteAlignment() != base.byteAlignment()) {
            base = base.withByteAlignment(v.byteAlignment());
            expr += ".withByteAlignment(" + v.byteAlignment() + ")";
        }
        if (!base.equals(v.withoutName())) {
            throw new IllegalStateException("cannot rebuild layout " + v + " (got " + base + ")");
        }
        return expr;
    }
}
