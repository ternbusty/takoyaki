package com.ternbusty.takoyaki.ffigen;

import java.io.IOException;
import java.lang.classfile.ClassFile;
import java.lang.classfile.constantpool.MethodRefEntry;
import java.lang.classfile.constantpool.PoolEntry;
import java.lang.reflect.Modifier;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashSet;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.Stream;

/**
 * Build-time generator for the symbol table of the fully static (musl) build.
 *
 * <p>A static executable has no dynamic linker, so dlopen and dlsym do not
 * work and none of the FFM lookups ({@code libraryLookup}, {@code loaderLookup},
 * {@code defaultLookup}) can resolve a symbol. The static build replaces
 * jextract's {@code SYMBOL_LOOKUP} with {@code StaticSymbolLookup}, which asks
 * a C table of name/address pairs that the linker fills in.
 *
 * <p>The table lists exactly the native functions the compiled main classes
 * call: every method reference to {@code NativeH} or a jextract header class
 * whose name is a jextract function. A function added to the Java code is
 * therefore in the table without any manual step, and a symbol musl does not
 * provide fails the link instead of the first call at run time.
 *
 * <p>Usage: {@code GenerateStaticSymbols <output .c file> <main classes dir>}
 */
public final class GenerateStaticSymbols {
    private static final String PKG = "com.ternbusty.takoyaki.syscall.gen";
    private static final String RAW = PKG + ".NativeHRaw";
    private static final String HEADER_PREFIX = PKG.replace('.', '/') + "/NativeH";

    private GenerateStaticSymbols() {}

    public static void main(String[] args) throws IOException {
        Path out = Path.of(args[0]);
        Path classes = Path.of(args[1]);

        Set<String> functions = jextractFunctions();
        Set<String> used = new TreeSet<>();
        try (Stream<Path> files = Files.walk(classes)) {
            for (Path file : (Iterable<Path>) files.filter(p -> p.toString().endsWith(".class"))::iterator) {
                var model = ClassFile.of().parse(file);
                // The bindings themselves reference every function they declare.
                if (model.thisClass().asInternalName().startsWith(HEADER_PREFIX)) continue;
                for (PoolEntry e : model.constantPool()) {
                    if (e instanceof MethodRefEntry ref
                            && ref.owner().asInternalName().startsWith(HEADER_PREFIX)
                            && functions.contains(ref.name().stringValue())) {
                        used.add(ref.name().stringValue());
                    }
                }
            }
        }
        if (used.isEmpty()) {
            throw new IllegalStateException("no native function references found under " + classes);
        }

        StringBuilder sb = new StringBuilder()
                .append("/* Generated by GenerateStaticSymbols; do not edit. */\n")
                .append("#include <string.h>\n")
                .append("#include \"native.h\"\n\n")
                .append("static const struct { const char *name; void *addr; } symbols[] = {\n");
        // Sorted by name for the binary search below.
        for (String name : used) {
            sb.append("    {\"").append(name).append("\", (void *)").append(name).append("},\n");
        }
        sb.append("};\n\n")
          .append("void *takoyaki_static_lookup(const char *name) {\n")
          .append("    size_t lo = 0, hi = sizeof(symbols) / sizeof(symbols[0]);\n")
          .append("    while (lo < hi) {\n")
          .append("        size_t mid = lo + (hi - lo) / 2;\n")
          .append("        int c = strcmp(name, symbols[mid].name);\n")
          .append("        if (c == 0) return symbols[mid].addr;\n")
          .append("        if (c < 0) hi = mid; else lo = mid + 1;\n")
          .append("    }\n")
          .append("    return NULL;\n")
          .append("}\n");
        Files.createDirectories(out.getParent());
        Files.writeString(out, sb);
        System.out.printf("GenerateStaticSymbols: %d of %d functions referenced%n",
                used.size(), functions.size());
    }

    /**
     * Names of the functions jextract bound: the holder classes nested in the
     * header classes. Function holders carry a {@code DESC} field; the public
     * holders are the variadic invokers.
     */
    private static Set<String> jextractFunctions() {
        Set<String> names = new HashSet<>();
        for (int i = 0; ; i++) {
            Class<?> header;
            try {
                header = Class.forName(i == 0 ? RAW : RAW + "_" + i, false,
                        GenerateStaticSymbols.class.getClassLoader());
            } catch (ClassNotFoundException e) {
                break;
            }
            for (Class<?> holder : header.getDeclaredClasses()) {
                if (Modifier.isPublic(holder.getModifiers()) || hasField(holder, "DESC")) {
                    names.add(holder.getSimpleName());
                }
            }
        }
        return names;
    }

    private static boolean hasField(Class<?> c, String name) {
        try {
            c.getDeclaredField(name);
            return true;
        } catch (NoSuchFieldException e) {
            return false;
        }
    }
}
